export function analyzeLocal(text: string, lang: Lang): AnalyzeResponse {
  const t0 = performance.now();

  if (!text.trim()) {
    return {
      score: 0,
      level: "safe",
      scheme: null,
      scheme_name: null,
      triggers: [],
      highlights: [],
      recommendations: RECS[lang].safe,
      processing_time_ms: Math.round((performance.now() - t0) * 100) / 100,
    };
  }

  let total = 0;
  const triggers: string[] = [];
  const highlights: HighlightSpan[] = [];
  const schemeScores: Record<string, number> = {};

  for (const rule of RULES) {
    const matches = [...text.matchAll(rule.re)];
    if (matches.length === 0) continue;
    total += rule.w;
    triggers.push(lang === "kz" ? rule.kz : rule.ru);
    if (rule.s) schemeScores[rule.s] = (schemeScores[rule.s] ?? 0) + rule.w;
    for (const m of matches) {
      const start = m.index ?? 0;
      highlights.push({ start, end: start + m[0].length, text: m[0] });
    }
  }

  total = Math.min(98, total);
  const level: RiskLevel = total >= 55 ? "risk" : total >= 25 ? "warn" : "safe";

  let scheme: string | null = null;
  const schemeIds = Object.keys(schemeScores);
  if (schemeIds.length > 0 && level !== "safe") {
    scheme = schemeIds.reduce((best, id) => (schemeScores[id] > schemeScores[best] ? id : best));
  }

  const uniqueTriggers = [...new Set(triggers)];
  const schemeName = scheme ? SCHEME_NAMES[scheme][lang] : null;

  return {
    score: total,
    level,
    scheme,
    scheme_name: schemeName,
    triggers: uniqueTriggers,
    highlights,
    recommendations: RECS[lang][level],
    processing_time_ms: Math.round((performance.now() - t0) * 100) / 100,
  };
}
