interface CompiledRule {
  re: RegExp;
  w: number;
  s: string | null;
  ru: string;
  kz: string;
}

// Python's `\w`/IGNORECASE are Unicode-aware; JS needs the `u` flag + \p{} and
// a Unicode-safe word boundary for the one Cyrillic-adjacent `\b`.
function compile(p: string): RegExp {
  const src = p
    .replace(/\\w/g, "[\\p{L}\\p{N}_]")
    .replace(/скинь\\b/g, "скинь(?![\\p{L}\\p{N}_])");
  return new RegExp(src, "giu");
}

